    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?,
    ): View? {
        return (layoutInflater.inflate(R.layout.fragment_quran, container, false))
    }

    lateinit var chaptersRecycler: RecyclerView

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        initRV(view)

    }

    val chaptersAdapter = ChaptersRecyclerAdapter(chaptersTittles)

    private fun initRV(view: View) {
        chaptersRecycler = view.findViewById(R.id.chapters_recycler)
        chaptersRecycler.adapter = chaptersAdapter
        chaptersAdapter.onItemClickListener =
            ChaptersRecyclerAdapter.OnItemClickLister { position, title ->
                startChapterDetailsActivity(position, title)
            }


    }

    private fun startChapterDetailsActivity(position: Int, title: String) {
        val intent = Intent(context, ChapterDetailsActivity::class.java)
        intent.putExtra(ChapterDetailsActivity.POSITION, position)
        intent.putExtra(ChapterDetailsActivity.TITLE, title)

        startActivity(intent)

    }
